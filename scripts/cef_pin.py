"""Write crates/manifold/src/cef_pin.rs: the CEF build the app downloads on demand.

Usage (from the repo root; stdout is the whole Rust file, so redirect it):

    python -P scripts/cef_pin.py <cef version prefix> > crates/manifold/src/cef_pin.rs
    # or: scripts/cef-pin.sh 152.0.6

It reads https://cef-builds.spotifycdn.com/index.json, picks the `windows64` `minimal` file whose
cef_version starts with "<prefix>+", downloads it ONCE (about 172 MB; running the script is the
confirmation, and the notice goes to stderr first) to a temp file, checks it against the index's
size and sha1, computes the SHA-256 (the index has none), deletes the temp file, and prints the
Rust table. If the check fails the temp file is deleted too; nothing is printed on stdout.

Re-pinning after a `cef` crate bump: look up the CEF build the new crate wraps (the part after
the `+` in its Cargo.lock version, e.g. `152.1.0+152.0.6` wraps CEF 152.0.6), update
CEF_CRATE_VERSION and CEF_BUILD_PREFIX next to `the_pin_matches_the_cef_crates_version` in
crates/manifold/src/engine_install.rs, then run this script with the new prefix and commit the
regenerated cef_pin.rs.
"""

import hashlib
import json
import os
import sys
import tempfile
import time
import urllib.parse
import urllib.request

BASE = "https://cef-builds.spotifycdn.com/"
PLATFORM = "windows64"
KIND = "minimal"

TEMPLATE = """\
//! The CEF build the app downloads on demand.
//! Generated by scripts/cef_pin.py (see its docstring to re-pin); do not edit by hand.

use crate::engine_install::Pin;

// Later install tasks use it.
#[allow(dead_code)]
pub(crate) const CEF_PIN: Pin = Pin {{
    version: "{version}",
    url: "{url}",
    size: {size},
    sha1: "{sha1}",
    sha256: "{sha256}",
}};
"""


def log(msg):
    print(msg, file=sys.stderr, flush=True)


def pick(index, prefix):
    versions = index[PLATFORM]["versions"]
    hits = []
    for v in versions:
        if v["cef_version"].startswith(prefix + "+"):
            files = [f for f in v["files"] if f["type"] == KIND]
            if files:
                hits.append((v["cef_version"], files[0]))
    if len(hits) != 1:
        sys.exit(f"expected exactly one {PLATFORM} {KIND} build for {prefix!r}, found {len(hits)}")
    return hits[0]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    prefix = sys.argv[1]
    with urllib.request.urlopen(BASE + "index.json", timeout=60) as r:
        index = json.load(r)
    version, f = pick(index, prefix)
    url = BASE + urllib.parse.quote(f["name"], safe="")
    size = int(f["size"])
    log(f"About to download {f['name']} ({size / 1e6:.1f} MB) from {url} to a temp file, once.")

    fd, tmp = tempfile.mkstemp(prefix="cef-pin-", suffix=".tar.bz2")
    os.close(fd)
    try:
        sha1, sha256 = hashlib.sha1(), hashlib.sha256()
        got, start, last = 0, time.monotonic(), 0.0
        with urllib.request.urlopen(url, timeout=60) as r, open(tmp, "wb") as out:
            while chunk := r.read(1 << 20):
                out.write(chunk)
                sha1.update(chunk)
                sha256.update(chunk)
                got += len(chunk)
                if time.monotonic() - last > 5:
                    last = time.monotonic()
                    log(f"  {got / 1e6:.1f} / {size / 1e6:.1f} MB")
        secs = time.monotonic() - start
        log(f"Downloaded {got} bytes in {secs:.1f} s ({got / 1e6 / secs:.2f} MB/s).")
        if got != size or sha1.hexdigest() != f["sha1"]:
            sys.exit(f"download does not match the index: {got} bytes sha1 {sha1.hexdigest()}, "
                     f"index says {size} bytes sha1 {f['sha1']}")
    finally:
        os.remove(tmp)

    sys.stdout.reconfigure(newline="\n")
    sys.stdout.write(TEMPLATE.format(version=version, url=url, size=f"{size:_}", sha1=f["sha1"],
                                     sha256=sha256.hexdigest()))


main()
