"""Update crates/manifold/src/cef_pin.rs: the CEF builds the app downloads on demand, one pin per platform.

Usage (from anywhere; the script rewrites the file itself):

    python -P scripts/cef_pin.py [--platform <cdn id>] <cef version prefix> < /dev/null
    # or: scripts/cef-pin.sh [--platform <cdn id>] 152.0.6

--platform is the CDN's platform id: windows64 (the default), linux64, macosx64 or macosarm64. It reads
https://cef-builds.spotifycdn.com/index.json, picks that platform's `minimal` file whose cef_version starts
with "<prefix>+", downloads it ONCE (about 172 MB for windows64; running the script is the confirmation, and
the notice goes to stderr first) to a temp file, checks it against the index's size and sha1, computes the
SHA-256 (the index has none), deletes the temp file, and replaces that platform's `// BEGIN <id>` block in
cef_pin.rs (adding it, and its arm in `pin_for`, when it is new). Other platforms' blocks are kept as they are.
If the check fails the temp file is deleted too and cef_pin.rs is left alone.

Re-pinning after a `cef` crate bump: look up the CEF build the new crate wraps (the part after the `+` in its
Cargo.lock version, e.g. `152.1.0+152.0.6` wraps CEF 152.0.6), update CEF_CRATE_VERSION and CEF_BUILD_PREFIX
next to `the_pin_matches_the_cef_crates_version` in crates/manifold/src/engine_install.rs, then run this script
once per pinned platform with the new prefix and commit the regenerated cef_pin.rs. Every pinned platform has
to move to the same CEF build (the shipped host links one CEF exactly), so each release re-pins all of them.
Adding a platform is the same command with its --platform, plus its `CefPlatform` in cef_platform.rs.
"""

import hashlib
import json
import os
import re
import sys
import tempfile
import time
import urllib.parse
import urllib.request

BASE = "https://cef-builds.spotifycdn.com/"
PLATFORMS = ("windows64", "linux64", "macosx64", "macosarm64")
KIND = "minimal"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "manifold", "src", "cef_pin.rs")

HEADER = """\
//! The CEF builds the app downloads on demand, one pin per CDN platform.
//! Generated by scripts/cef_pin.py (see its docstring to re-pin); do not edit by hand.

use crate::engine_install::Pin;
"""

BLOCK = """\
// BEGIN {platform}
pub(crate) const PIN_{upper}: Pin = Pin {{
    version: "{version}",
    url: "{url}",
    size: {size},
    sha1: "{sha1}",
    sha256: "{sha256}",
}};
// END {platform}
"""

LOOKUP = """\
/// The pin for CDN platform `id` (`CefPlatform::id`), or `None` while that platform has none.
pub(crate) fn pin_for(id: &str) -> Option<&'static Pin> {{
    match id {{
{arms}        _ => None,
    }}
}}

/// The pin for the platform this build runs on: `None` where no CEF build is pinned yet.
pub(crate) fn pin_for_platform() -> Option<&'static Pin> {{
    pin_for(crate::cef_platform::PLATFORM.id)
}}
"""


def log(msg):
    print(msg, file=sys.stderr, flush=True)


def pick(index, platform, prefix):
    hits = []
    for v in index[platform]["versions"]:
        if v["cef_version"].startswith(prefix + "+"):
            files = [f for f in v["files"] if f["type"] == KIND]
            if files:
                hits.append((v["cef_version"], files[0]))
    if len(hits) != 1:
        sys.exit(f"expected exactly one {platform} {KIND} build for {prefix!r}, found {len(hits)}")
    return hits[0]


def blocks_of(text):
    """The `// BEGIN <platform>` ... `// END <platform>` blocks of an existing cef_pin.rs, by platform."""
    return {m.group(1): m.group(0) for m in re.finditer(r"// BEGIN (\w+)\n.*?// END \1\n", text, re.S)}


def render(blocks):
    """The whole cef_pin.rs for `blocks` (platform -> block text), platforms in a fixed order."""
    order = [p for p in PLATFORMS if p in blocks]
    arms = "".join(f'        "{p}" => Some(&PIN_{p.upper()}),\n' for p in order)
    return "\n".join([HEADER, "\n".join(blocks[p] for p in order), LOOKUP.format(arms=arms)])


def main():
    args = sys.argv[1:]
    platform = "windows64"
    if args[:1] == ["--platform"] and len(args) >= 2:
        platform, args = args[1], args[2:]
    if len(args) != 1 or platform not in PLATFORMS:
        sys.exit(__doc__)
    prefix = args[0]
    with urllib.request.urlopen(BASE + "index.json", timeout=60) as r:
        index = json.load(r)
    version, f = pick(index, platform, prefix)
    url = BASE + urllib.parse.quote(f["name"], safe="")
    size = int(f["size"])
    log(f"About to download {f['name']} ({size / 1e6:.1f} MB) from {url} to a temp file, once.")

    fd, tmp = tempfile.mkstemp(prefix="cef-pin-", suffix=".tar.bz2")
    os.close(fd)
    try:
        sha1, sha256 = hashlib.sha1(), hashlib.sha256()
        got, start, last = 0, time.monotonic(), 0.0
        with urllib.request.urlopen(url, timeout=60) as r, open(tmp, "wb") as out:
            while chunk := r.read(1 << 20):
                out.write(chunk)
                sha1.update(chunk)
                sha256.update(chunk)
                got += len(chunk)
                if time.monotonic() - last > 5:
                    last = time.monotonic()
                    log(f"  {got / 1e6:.1f} / {size / 1e6:.1f} MB")
        secs = time.monotonic() - start
        log(f"Downloaded {got} bytes in {secs:.1f} s ({got / 1e6 / secs:.2f} MB/s).")
        if got != size or sha1.hexdigest() != f["sha1"]:
            sys.exit(f"download does not match the index: {got} bytes sha1 {sha1.hexdigest()}, "
                     f"index says {size} bytes sha1 {f['sha1']}")
    finally:
        os.remove(tmp)

    try:
        with open(OUT, encoding="utf-8", newline="") as fh:
            blocks = blocks_of(fh.read())
    except FileNotFoundError:
        blocks = {}
    blocks[platform] = BLOCK.format(platform=platform, upper=platform.upper(), version=version, url=url,
                                    size=f"{size:_}", sha1=f["sha1"], sha256=sha256.hexdigest())
    new = OUT + ".new"
    with open(new, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(blocks))
    os.replace(new, OUT)
    log(f"Wrote {os.path.normpath(OUT)}.")


if __name__ == "__main__":
    main()
